function checklist(
  organizationId: string,
  jobId: string,
  items: [string, boolean, boolean?][],
  completedAt: string | null,
): ChecklistItem[] {
  return items.map(([label, required, done], index) => ({
    id: `${jobId}_chk_${index + 1}`,
    organizationId,
    jobId,
    label,
    required,
    completed: Boolean(done),
    position: index + 1,
    completedAt: done ? completedAt : null,
  }));
}

