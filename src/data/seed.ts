export function parseDatabase(raw: string | null, now: Date): Database {
  if (!raw) return buildSeed(now);
  try {
    const parsed = JSON.parse(raw) as Database;
    if (!parsed || parsed.version !== SEED_VERSION || !Array.isArray(parsed.jobs) || !Array.isArray(parsed.members)) {
      return buildSeed(now);
    }
    return parsed;
  } catch {
    return buildSeed(now);
  }
}

function job(
  input: Omit<Job, 'currency' | 'scheduledStart' | 'scheduledEnd' | 'travelStartedAt' | 'startedAt' | 'pausedAt' | 'completedAt'> &
    Partial<Pick<Job, 'travelStartedAt' | 'startedAt' | 'pausedAt' | 'completedAt'>> & {
      start: string;
      end: string;
    },
): Job {
  const { start, end, travelStartedAt, startedAt, pausedAt, completedAt, ...rest } = input;
  return {
    ...rest,
    currency: 'usd',
    scheduledStart: start,
    scheduledEnd: end,
    travelStartedAt: travelStartedAt ?? null,
    startedAt: startedAt ?? null,
    pausedAt: pausedAt ?? null,
    completedAt: completedAt ?? null,
  };
}

function loc(
  organizationId: string,
  id: string,
  customerId: string,
  label: string,
  line1: string,
  city: string,
  region: string,
  postalCode: string,
  lat: number,
  lng: number,
) {
  return { id, organizationId, customerId, label, line1, city, region, postalCode, lat, lng };
}
